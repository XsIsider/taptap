def cell(value):
    return str(value).replace('|', '／').replace('\n', ' ')


def room_name(room_id):
    room = indexes['Room'].get(room_id)
    if not room:
        return '承接当前场景'
    name = '仓库／中控室' if room_id == 100003 else room['Name']
    return f"{room['Floor']}F · {name}"


def condition_name(condition):
    kind, raw_id = condition.split(':', 1)
    item_id = int(raw_id)
    if kind == 'goal':
        found = next((e for e in data['Event'] if e['Goal'] == item_id), None)
        name = '完成：' + found['Name'] if found else condition
    else:
        table = {'entry': 'Entry', 'puzzle': 'Puzzle'}.get(kind)
        name = indexes[table][item_id]['Name'] if table and item_id in indexes[table] else condition
    return cell(name)


